/**
 * Marks reachable under a second spelling, so an id that moved group or a legacy slug
 * still finds its artwork: the React Query name TanStack shipped before its rebrand,
 * and the hyphenated form of the same library.
 */
const BRAND_ALIASES: Record<string, string> = {
  reactquery: 'tanstack-query',
  'react-query': 'tanstack-query',
  tanstack: 'tanstack-query',
  rtk: 'redux',
  'redux-toolkit': 'redux',
  'react-redux': 'redux',
  mst: 'mobx',
  'mobx-state-tree': 'mobx',
  wandb: 'weights-and-biases',
  idb: 'indexeddb',
  localstorage: 'local-storage',
  k8s: 'kubernetes',
};

/** The id a stored slug resolves to: its own entry, or the canonical one it aliases. */
function resolveBrandId(id: string) {
  const key = id.toLowerCase();
  return BRAND_ICONS[key] ? key : BRAND_ALIASES[key];
}

/** True when a stored slug has official artwork — drives the resolver's first tier. */
export function hasBrandIcon(id: string) {
  return Boolean(resolveBrandId(id));
}

/**
 * A brand mark on the shared monochrome surface: a single `currentColor` path, so it
 * takes the pill's ink and inverts with it on hover, exactly like the Lucide glyphs
 * beside it. `aria-hidden` — the accessible name lives on the text next to it.
 */
export function BrandGlyph({ id, className }: { id: string; className?: string }) {
  const brandId = resolveBrandId(id);
  const icon = brandId ? BRAND_ICONS[brandId] : undefined;
  if (!icon) return null;
  return (
    <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" className={className}>
      <path d={icon.path} />
    </svg>
  );
}

/**
 * The one glyph the toolkit uses, in both the dashboard and the public pills.
 *
 * A brand that ships real artwork gets it; everything else falls through to the shared
 * `iconDecider` registry — a neutral conceptual glyph, or `BookOpen` for a stale slug —
 * so an unknown value still renders beside its correct name rather than vanishing. This
 * keeps the public site and the admin preview drawing the identical mark.
 */
export function SkillGlyph({ id, className }: { id?: string | null; className?: string }) {
  if (!id) return null;
  if (hasBrandIcon(id)) return <BrandGlyph id={id} className={className} />;
  return iconDecider(id, className);
}
